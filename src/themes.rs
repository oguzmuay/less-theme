/// Sıra: 0 bg, 1 bg_dark, 2 bg_highlight, 3 fg, 4 fg_dim, 5 comment, 6 accent, 7 icon, 8 error, 9 surface,
/// 10 border, 11 on_accent; sözdizimi 12 keyword, 13 string, 14 number, 15 function, 16 type, 17 annotation,
/// 18 syntax comment; ek 19 variable, 20 constant, 21 operator, 22 punctuation, 23 tag, 24 property,
/// 25 namespace, 26 diff add, 27 diff delete, 28 diff change, 29 warn, 30 info, 31 hint.
const fn build(id: &'static str, name: &'static str, dark: bool, v: [u32; 32]) -> Palette {
    Palette {
        id,
        name,
        dark,
        bg: Rgb::hex(v[0]),
        bg_dark: Rgb::hex(v[1]),
        bg_highlight: Rgb::hex(v[2]),
        fg: Rgb::hex(v[3]),
        fg_dim: Rgb::hex(v[4]),
        comment: Rgb::hex(v[5]),
        accent: Rgb::hex(v[6]),
        icon: Rgb::hex(v[7]),
        error: Rgb::hex(v[8]),
        surface: Rgb::hex(v[9]),
        border: Rgb::hex(v[10]),
        on_accent: Rgb::hex(v[11]),
        avatars: if dark { DARK_AVATARS } else { LIGHT_AVATARS },
        syntax: Syntax {
            keyword: Rgb::hex(v[12]),
            string: Rgb::hex(v[13]),
            number: Rgb::hex(v[14]),
            function: Rgb::hex(v[15]),
            ty: Rgb::hex(v[16]),
            annotation: Rgb::hex(v[17]),
            comment: Rgb::hex(v[18]),
        },
        extra: Extra::new([v[19], v[20], v[21], v[22], v[23], v[24], v[25], v[26], v[27], v[28], v[29], v[30], v[31]]),
    }
}

